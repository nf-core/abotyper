"""Make conda @EXPLICIT lock files for the nf-core modules.

conf/containers_conda_lock_files_{amd64,arm64}.config (generated by nf-core tools,
left unchanged) point at pixi-format (version: 6) module locks, which
`conda create --file` cannot read. This writes an @EXPLICIT copy of each lock to
assets/conda-lock/ and conf/conda_lock_explicit_{amd64,arm64}.config pointing at them.

Run from the pipeline root: python assets/conda-lock/make_explicit_locks.py
Only uses the URLs and md5s already in the locks. Safe to re-run.
"""
import re
import sys
from pathlib import Path

import yaml

OUT_DIR = Path("assets/conda-lock")
LINE = re.compile(r"""^process \{ withName: '(?P<name>[^']+)' \{ conda = ['"](?P<path>[^'"]+)['"] \} \}$""")
HEADER = (
    "// Pinned conda environments for the nf-core modules, as conda @EXPLICIT files.\n"
    "// Converted from the module locks in %s, which conda cannot read.\n"
    "// Use with: -profile conda -c conf/conda_lock_explicit_%s.config\n"
    "// Generated by assets/conda-lock/make_explicit_locks.py; do not edit by hand.\n"
)


CONDA = re.compile(r"^\s*- conda: (\S+)\s*$")
MD5 = re.compile(r"^\s*md5: ([0-9a-f]{32})\s*$")
PLATFORM = re.compile(r"^\s*(linux-64|linux-aarch64|osx-64|osx-arm64):\s*$")


def read_lines(text: str):
    """Line-based reader. Works on the valid locks and on the flattened (unindented) MultiQC
    lock that nf-core/modules ships, which YAML parsers reject."""
    lines = text.strip().splitlines()
    assert lines[0].strip() == "version: 6", "unexpected lock version"
    assert not any(l.lstrip().startswith("- pypi:") for l in lines), "pypi packages"
    platforms = {m[1] for l in lines if (m := PLATFORM.match(l))}
    assert len(platforms) == 1, f"expected one platform, got {platforms}"
    urls, md5, current = [], {}, None
    for l in lines:
        if m := CONDA.match(l):
            current = m[1]
            if current not in urls:
                urls.append(current)
        elif (m := MD5.match(l)) and current:
            md5[current] = m[1]
            current = None
    return platforms.pop(), urls, md5


def convert(src: Path) -> Path:
    text = src.read_text(encoding="utf-8")
    platform, urls, md5 = read_lines(text)
    try:
        lock = yaml.safe_load(text)
    except yaml.YAMLError:
        print(f"  note: {src} is not valid YAML; read line by line")
    else:  # cross-check the line reader against a real parse
        (yp, pkgs), = lock["environments"]["default"]["packages"].items()
        assert yp == platform and [p["conda"] for p in pkgs] == urls, f"{src}: reader mismatch"
        assert md5 == {p["conda"]: p["md5"] for p in lock["packages"]}, f"{src}: md5 mismatch"
    assert urls, f"{src}: no packages"
    missing = [u for u in urls if u not in md5]
    assert not missing, f"{src}: no md5 for {missing}"

    tool = src.parts[2]  # modules/nf-core/<tool>/...
    dest = OUT_DIR / f"{tool}-{src.name}"
    body = (
        f"# Generated from {src.as_posix()}\n"
        f"# platform: {platform}\n"
        "@EXPLICIT\n" + "".join(f"{u}#{md5[u]}\n" for u in urls)
    )
    if dest.exists():
        assert dest.read_text(encoding="utf-8").split("\n", 1)[1] == body.split("\n", 1)[1], f"{dest}: clash"
    dest.write_text(body, encoding="utf-8", newline="\n")
    print(f"{src} -> {dest} ({platform}, {len(urls)} packages)")
    return dest


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    written = set()
    for arch in ("amd64", "arm64"):
        src_cfg = Path(f"conf/containers_conda_lock_files_{arch}.config")  # generated by nf-core tools
        dst_cfg = Path(f"conf/conda_lock_explicit_{arch}.config")
        out = [HEADER % (src_cfg.as_posix(), arch)]
        for line in src_cfg.read_text(encoding="utf-8").splitlines():
            if not line.strip() or line.startswith("//"):
                continue
            m = LINE.match(line)
            assert m, f"{src_cfg}: unexpected line {line!r}"
            dest = convert(Path(m["path"]))
            written.add(dest)
            out.append("process { withName: '%s' { conda = \"${projectDir}/%s\" } }\n" % (m["name"], dest.as_posix()))
        dst_cfg.write_text("".join(out), encoding="utf-8", newline="\n")
        print(f"wrote {dst_cfg}")
    for stale in set(OUT_DIR.glob("*.txt")) - written:  # locks of modules that were updated or removed
        stale.unlink()
        print(f"removed {stale}")
    print("ok")


if __name__ == "__main__":
    sys.exit(main())
