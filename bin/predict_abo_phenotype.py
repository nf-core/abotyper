@dataclass
class PositionData:
    """Data class for nucleotide position information."""
    ref_base: str
    match_percent: float
    mismatch_percent: float
    insertion_percent: float
    deletion_percent: float
    A_percent: float
    G_percent: float
    C_percent: float
    T_percent: float
    coverage: int = 0


@dataclass
class CoverageInfo:
    """Data class for coverage information."""
    numreads: int = 0
    covbases: int = 0


class ABOPhenotypePredictor:
    """Main class for ABO phenotype prediction. Panel-driven (v2.0.0)."""

    # Reference length used only as a fallback hint when a filename gives no
    # clue about which exon(s) are present. With the combined exon2-7
    # amplicon this heuristic is much less meaningful than in v1.x (two
    # short separate amplicons) -- prefer --exon / filename detection.
    EXON6_MIN_LENGTH = 135

    def __init__(self, panel: Panel, loglevel: str = "INFO"):
        """Initialize the predictor with logging configuration and a loaded panel."""
        self.panel = panel
        self._setup_logging(loglevel)
        self.logger.info("=" * 80)
        self.logger.info(f"ABO Blood Type Prediction Script v{__version__} - Started at {datetime.datetime.now()}")
        self.logger.info(f"Panel: {len(panel.variants)} variants across exons: {', '.join(panel.exons())}")
        self.logger.info("=" * 80)

    def _setup_logging(self, loglevel: str) -> None:
        """Setup logging configuration."""
        logging.basicConfig(
            level=getattr(logging, loglevel.upper()),
            format='[%(asctime)s] %(levelname)s: %(message)s',
            datefmt='%Y-%m-%d %H:%M:%S'
        )
        self.logger = logging.getLogger(__name__)

    @staticmethod
    def format_number(value: float) -> str:
        """Format number as integer if whole, otherwise as float with 2 decimals."""
        if abs(value - round(value)) < 1e-10:
            return f"{int(value)}"
        else:
            return f"{value:.2f}"

    def read_nucleotide_frequencies(self, input_file: Union[str, Path]) -> Tuple[Dict[int, PositionData], int, bool]:
        """
        Read nucleotide frequency data from input file.

        Args:
            input_file: Path to input file

        Returns:
            Tuple of (positions dict, max_position, is_empty_file)
        """
        input_path = Path(input_file)
        self.logger.info(f"Reading nucleotide frequencies from: {input_path}")

        if not input_path.exists():
            self.logger.error(f"Input file does not exist: {input_path}")
            return {}, 0, True

        if input_path.stat().st_size == 0:
            self.logger.warning(f"Input file {input_path} is empty")
            return {}, 0, True

        try:
            df = pd.read_csv(input_path, sep="\t")
            self.logger.debug(f"Data shape: {df.shape}")
            self.logger.debug(f"Columns found: {list(df.columns)}")

            if df.empty:
                self.logger.warning("Input file contains no data rows")
                return {}, 0, True

            positions = {}
            max_position = 0
            valid_row_count = 0

            required_columns = [
                "Ref_Position_1based", "Ref_Base", "Match_Percent", "Mismatch_Percent",
                "Insertion_Percent", "Deletion_Percent", "A_Percent", "G_Percent",
                "C_Percent", "T_Percent"
            ]

            missing_columns = [col for col in required_columns if col not in df.columns]
            if missing_columns:
                self.logger.error(f"Missing required columns: {missing_columns}")
                return {}, 0, True

            for index, row in df.iterrows():
                try:
                    pos = int(row["Ref_Position_1based"])

                    position_data = PositionData(
                        ref_base=row["Ref_Base"],
                        match_percent=float(row["Match_Percent"]),
                        mismatch_percent=float(row["Mismatch_Percent"]),
                        insertion_percent=float(row["Insertion_Percent"]),
                        deletion_percent=float(row["Deletion_Percent"]),
                        A_percent=float(row["A_Percent"]),
                        G_percent=float(row["G_Percent"]),
                        C_percent=float(row["C_Percent"]),
                        T_percent=float(row["T_Percent"])
                    )

                    positions[pos] = position_data
                    max_position = max(max_position, pos)
                    valid_row_count += 1

                except (ValueError, KeyError) as e:
                    self.logger.warning(f"Could not parse row {index}: {e}")
                    continue

            self.logger.info(f"Successfully processed {valid_row_count} positions, max position: {max_position}")
            return positions, max_position, False

        except Exception as e:
            self.logger.error(f"Error reading nucleotide frequency file: {e}")
            return {}, 0, True

    def read_coverage_file(self, coverage_file: Union[str, Path]) -> Optional[CoverageInfo]:
        """Read coverage information from coverage statistics file."""
        coverage_path = Path(coverage_file)
        self.logger.info(f"Reading coverage information from: {coverage_path}")

        if not coverage_path.exists():
            self.logger.warning(f"Coverage file does not exist: {coverage_path}")
            return None

        try:
            df = pd.read_csv(coverage_path, sep="\t", comment=None)

            if df.empty:
                self.logger.warning("Coverage file has no data rows")
                return None

            self.logger.debug(f"Found {len(df)} data rows with columns: {list(df.columns)}")

            numreads_col = None
            coverage_col = None

            for col in df.columns:
                col_lower = col.lower()
                if "numreads" in col_lower and numreads_col is None:
                    numreads_col = col
                elif "coverage" in col_lower and coverage_col is None:
                    coverage_col = col

            if numreads_col and coverage_col:
                numreads = int(df.iloc[0][numreads_col])
                coverage = int(df.iloc[0][coverage_col])

                coverage_info = CoverageInfo(numreads=numreads, covbases=coverage)
                self.logger.info(f"Extracted coverage info: numreads={numreads}, coverage={coverage}")
                return coverage_info
            else:
                self.logger.warning(f"Required columns not found. Available columns: {list(df.columns)}")
                return None

        except Exception as e:
            self.logger.error(f"Error reading coverage file: {e}")
            return None

    def determine_exons_present(self, filename: str, positions: Dict[int, PositionData]) -> List[str]:
        """
        Determine which exon(s) (as labelled in the panel) this input file's
        positions correspond to.

        With the combined exon2-7 amplicon a single input file may in
        principle cover several exons at once (e.g. one AlignmentStatistics.tsv
        for the whole reference). We resolve this generically: for every
        exon the panel knows about, check whether we have position data at
        any of that exon's resolved (calibrated) panel positions.

        Falls back to filename substring matching ("exon6"/"exon7"/...),
        matching v1.x behaviour, when no panel positions match (e.g. running
        against legacy mini-amplicon files that only contain a handful of
        positions and no distinctive filename hint).
        """
        exons_found = []
        for exon_label in self.panel.exons():
            exon_positions = [
                m.resolved_position() for m in self.panel.by_exon(exon_label)
                if m.resolved_position() is not None
            ]
            if any(p in positions for p in exon_positions):
                exons_found.append(exon_label)

        if exons_found:
            self.logger.info(f"Exons detected from position overlap: {exons_found}")
            return exons_found

        filename_lower = filename.lower()
        for exon_label in self.panel.exons():
            token = exon_label.lower().replace(" ", "")
            if token in filename_lower.replace(" ", ""):
                self.logger.info(f"Exon detected from filename: {exon_label}")
                return [exon_label]

        # Legacy fallback for exon6-vs-exon7-only naming used by v1.x callers
        if "exon6" in filename_lower:
            return ["Exon 6"]
        if "exon7" in filename_lower:
            return ["Exon 7"]

        self.logger.warning(
            "Could not determine which exon(s) this file covers from "
            "filename or position overlap; report may be incomplete."
        )
        return []

    def generate_exon_report(
        self,
        exon_label: str,
        positions: Dict[int, PositionData],
        output_file: Union[str, Path],
        coverage_info: Optional[CoverageInfo] = None,
        append: bool = False,
    ) -> None:
        """Generate a report section for one exon, driven entirely by the panel."""
        output_path = Path(output_file)
        self.logger.info(f"Generating {exon_label} report to: {output_path}")

        coverage_display = ""
        if coverage_info:
            coverage_display = f" (reads={coverage_info.numreads}, cov={coverage_info.covbases})"

        markers = self.panel.by_exon(exon_label)
        primary_markers = [m for m in markers if m.category == "primary"]
        subtype_markers = [m for m in markers if m.category != "primary"]

        mode = "a" if append else "w"
        try:
            with open(output_path, mode) as f:
                f.write(f"{exon_label}:\n")

                for marker in primary_markers:
                    self._write_marker(f, marker, positions, coverage_display, exon_label)

                available_subtype = [
                    m for m in subtype_markers
                    if m.resolved_position() in positions
                ]
                if available_subtype:
                    f.write("\n# -------- Subtype / null-allele variants --------\n")
                    for marker in sorted(
                        available_subtype, key=lambda m: m.resolved_position() or 0
                    ):
                        self._write_marker(f, marker, positions, coverage_display, exon_label)

            self.logger.info(f"[OK] {exon_label} report successfully written to {output_path}")

        except Exception as e:
            self.logger.error(f"Error generating {exon_label} report: {e}")
            if not append:
                self._create_empty_file(output_path)

    def _write_marker(
        self,
        file_handle,
        marker: VariantMarker,
        positions: Dict[int, PositionData],
        coverage_display: str,
        exon_label: str,
    ) -> None:
        """Write one marker's raw data + interpretation, panel-driven."""
        pos = marker.resolved_position()
        if pos is None:
            self.logger.debug(
                f"Skipping {marker.id} ({marker.cdna_change}): no resolved "
                f"position yet (needs calibrate_panel_positions.py or a "
                f"legacy coordinate)."
            )
            return
        if pos not in positions:
            self.logger.debug(f"Position {pos} ({marker.cdna_change}) not found in data")
            return

        pos_data = positions[pos]
        exon_num = "".join(ch for ch in exon_label if ch.isdigit()) or "?"

        file_handle.write(f"\n{exon_label} position(1-based): {pos}\n")

        if marker.interpretation_ref:
            file_handle.write(f"{marker.interpretation_ref}\n")
        if marker.interpretation_alt:
            file_handle.write(f"{marker.interpretation_alt}\n")

        file_handle.write(f"(1-based) Position:{pos}, Reference Base={pos_data.ref_base}\n")
        file_handle.write(f"Aligned Read Count:{pos_data.coverage}{coverage_display}\n")
        file_handle.write("Mat\tMis\tIns\tDel\tA\tG\tC\tT\n")
        file_handle.write(
            f"{self.format_number(pos_data.match_percent)}\t"
            f"{self.format_number(pos_data.mismatch_percent)}\t"
            f"{self.format_number(pos_data.insertion_percent)}\t"
            f"{self.format_number(pos_data.deletion_percent)}\t"
            f"{self.format_number(pos_data.A_percent)}\t"
            f"{self.format_number(pos_data.G_percent)}\t"
            f"{self.format_number(pos_data.C_percent)}\t"
            f"{self.format_number(pos_data.T_percent)}\n"
        )

    def _create_empty_file(self, output_path: Path) -> None:
        """Create an empty output file."""
        try:
            output_path.touch()
            self.logger.info(f"Empty file created: {output_path}")
        except Exception as e:
            self.logger.error(f"Failed to create empty file {output_path}: {e}")

    def process_sample(
        self,
        input_file: Union[str, Path],
        output_file: Union[str, Path],
        coverage_file: Optional[Union[str, Path]] = None,
        exon: Optional[str] = None,
    ) -> bool:
        """
        Process a single sample for ABO phenotype prediction.

        Args:
            input_file: Input nucleotide frequency file
            output_file: Output report file
            coverage_file: Optional coverage statistics file
            exon: Optional explicit exon label (e.g. "Exon 6"); if omitted,
                  exon(s) are inferred from filename / position overlap and
                  ALL matching exons are written to the same output file.

        Returns:
            True if processing successful, False otherwise
        """
        try:
            self.logger.info("=" * 60)
            self.logger.info("Starting ABO phenotype prediction")
            self.logger.info("=" * 60)

            positions, max_position, empty_file = self.read_nucleotide_frequencies(input_file)

            if empty_file or not positions:
                self.logger.warning("No data available. Creating empty output file.")
                self._create_empty_file(Path(output_file))
                return False

            coverage_info = None
            if coverage_file:
                coverage_info = self.read_coverage_file(coverage_file)
                if coverage_info:
                    for pos_data in positions.values():
                        pos_data.coverage = coverage_info.numreads

            if exon:
                exon_labels = [exon]
            else:
                exon_labels = self.determine_exons_present(str(input_file), positions)

            if not exon_labels:
                self.logger.error("No exon could be determined; cannot generate report.")
                self._create_empty_file(Path(output_file))
                return False

            for i, exon_label in enumerate(exon_labels):
                self.generate_exon_report(
                    exon_label, positions, output_file, coverage_info,
                    append=(i > 0),
                )

            self.logger.info(f"[OK] ABO phenotype metrics written to: {output_file}")
            return True

        except Exception as e:
            self.logger.error(f"Error processing sample: {e}")
            self._create_empty_file(Path(output_file))
            return False


def main():
    """Main function to process nucleotide frequencies into ABO phenotypes."""
    parser = argparse.ArgumentParser(
        description="Extract metrics for ABO typing positions from nucleotide frequency data.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
    %(prog)s -i input.txt -o output.txt
    %(prog)s -i input.txt -o output.txt -c coverage.txt -e "Exon 6"
    %(prog)s -i input.txt -o output.txt --panel abo_variant_panel.yaml --verbose
        """
    )

    parser.add_argument("-i", "--input", required=True,
                         help="Input SAMtools mpileup / pysam_haploscan nucleotide variants metrics file")
    parser.add_argument("-o", "--output", required=True,
                         help="Output filename for ABO phenotype report")
    parser.add_argument("-c", "--coverage",
                         help="Input SAMtools coverage statistics file")
    parser.add_argument("-e", "--exon",
                         help='Explicitly specify which exon this file covers (e.g. "Exon 6"); '
                              "default: auto-detect from filename/position overlap and report "
                              "every matching exon.")
    parser.add_argument("--panel", default="abo_variant_panel.yaml",
                         help="Path to the variant panel file (.yaml/.json/.csv/.tsv). "
                              "Default: %(default)s")
    parser.add_argument("--verbose", "-v", action="store_true", help="Enable verbose logging")
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")

    args = parser.parse_args()

    loglevel = "DEBUG" if args.verbose else "INFO"

    try:
        panel = load_panel(args.panel)
    except Exception as exc:
        print(f"! CRITICAL: could not load variant panel '{args.panel}': {exc}")
        sys.exit(1)

    predictor = ABOPhenotypePredictor(panel=panel, loglevel=loglevel)

    success = predictor.process_sample(
        input_file=args.input,
        output_file=args.output,
        coverage_file=args.coverage,
        exon=args.exon,
    )

    if success:
        predictor.logger.info(f"Script execution completed successfully at: {datetime.datetime.now()}")
        sys.exit(0)
    else:
        predictor.logger.error("Script execution failed")
        sys.exit(1)


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\n! Script interrupted by user")
        sys.exit(130)
    except Exception as e:
        print(f"! CRITICAL ERROR: Unhandled exception: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)
