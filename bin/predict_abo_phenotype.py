class ExonType(Enum):
    """Enumeration for exon types."""
    EXON6 = "exon6"
    EXON7 = "exon7"


@dataclass
class PositionData:
    """Data class for nucleotide position information."""
    ref_base: str
    match_percent: float
    mismatch_percent: float
    insertion_percent: float
    deletion_percent: float
    A_percent: float
    G_percent: float
    C_percent: float
    T_percent: float
    coverage: int = 0


@dataclass
class CoverageInfo:
    """Data class for coverage information."""
    numreads: int = 0
    covbases: int = 0


class ABOPhenotypePredictor:
    """Main class for ABO phenotype prediction."""

    # Class constants for positions
    EXON6_POSITIONS = {
        'primary': [22],  # c.261 - Primary ABO*O1 marker
        'a_subtype': [27, 29, 58]  # c.266, c.268, c.297 - A subtype markers
    }

    EXON7_POSITIONS = {
        'primary': [422, 428, 429, 431],  # Primary diagnostic positions
        'a_subtype': [93, 165, 272, 307, 371, 446, 680, 687]  # A subtype positions
    }

    EXON6_MIN_LENGTH = 135  # Base pairs

    def __init__(self, loglevel: str = "INFO"):
        """Initialize the predictor with logging configuration."""
        self._setup_logging(loglevel)
        self.logger.info("=" * 80)
        self.logger.info(f"ABO Blood Type Prediction Script - Started at {datetime.datetime.now()}")
        self.logger.info("=" * 80)

    def _setup_logging(self, loglevel: str) -> None:
        """Setup logging configuration."""
        logging.basicConfig(
            level=getattr(logging, loglevel.upper()),
            format='[%(asctime)s] %(levelname)s: %(message)s',
            datefmt='%Y-%m-%d %H:%M:%S'
        )
        self.logger = logging.getLogger(__name__)

    @staticmethod
    def format_number(value: float) -> str:
        """Format number as integer if whole, otherwise as float with 2 decimals."""
        if abs(value - round(value)) < 1e-10:
            return f"{int(value)}"
        else:
            return f"{value:.2f}"

    def read_nucleotide_frequencies(self, input_file: Union[str, Path]) -> Tuple[Dict[int, PositionData], int, bool]:
        """
        Read nucleotide frequency data from input file.

        Args:
            input_file: Path to input file

        Returns:
            Tuple of (positions dict, max_position, is_empty_file)
        """
        input_path = Path(input_file)
        self.logger.info(f"Reading nucleotide frequencies from: {input_path}")

        if not input_path.exists():
            self.logger.error(f"Input file does not exist: {input_path}")
            return {}, 0, True

        if input_path.stat().st_size == 0:
            self.logger.warning(f"Input file {input_path} is empty")
            return {}, 0, True

        try:
            df = pd.read_csv(input_path, sep="\t")
            self.logger.debug(f"Data shape: {df.shape}")
            self.logger.debug(f"Columns found: {list(df.columns)}")

            if df.empty or len(df) < self.EXON6_MIN_LENGTH - 1:
                self.logger.warning(f"Input file contains insufficient data ({len(df)} rows)")
                return {}, 0, True

            positions = {}
            max_position = 0
            valid_row_count = 0

            required_columns = [
                "Ref_Position_1based", "Ref_Base", "Match_Percent", "Mismatch_Percent",
                "Insertion_Percent", "Deletion_Percent", "A_Percent", "G_Percent",
                "C_Percent", "T_Percent"
            ]

            missing_columns = [col for col in required_columns if col not in df.columns]
            if missing_columns:
                self.logger.error(f"Missing required columns: {missing_columns}")
                return {}, 0, True

            for index, row in df.iterrows():
                try:
                    pos = int(row["Ref_Position_1based"])

                    position_data = PositionData(
                        ref_base=row["Ref_Base"],
                        match_percent=float(row["Match_Percent"]),
                        mismatch_percent=float(row["Mismatch_Percent"]),
                        insertion_percent=float(row["Insertion_Percent"]),
                        deletion_percent=float(row["Deletion_Percent"]),
                        A_percent=float(row["A_Percent"]),
                        G_percent=float(row["G_Percent"]),
                        C_percent=float(row["C_Percent"]),
                        T_percent=float(row["T_Percent"])
                    )

                    positions[pos] = position_data
                    max_position = max(max_position, pos)
                    valid_row_count += 1

                except (ValueError, KeyError) as e:
                    self.logger.warning(f"Could not parse row {index}: {e}")
                    continue

            self.logger.info(f"Successfully processed {valid_row_count} positions, max position: {max_position}")
            return positions, max_position, False

        except Exception as e:
            self.logger.error(f"Error reading nucleotide frequency file: {e}")
            return {}, 0, True

    def read_coverage_file(self, coverage_file: Union[str, Path]) -> Optional[CoverageInfo]:
        """
        Read coverage information from coverage statistics file.

        Args:
            coverage_file: Path to coverage file

        Returns:
            CoverageInfo object or None if reading fails
        """
        coverage_path = Path(coverage_file)
        self.logger.info(f"Reading coverage information from: {coverage_path}")

        if not coverage_path.exists():
            self.logger.warning(f"Coverage file does not exist: {coverage_path}")
            return None

        try:
            df = pd.read_csv(coverage_path, sep="\t", comment=None)

            if df.empty:
                self.logger.warning("Coverage file has no data rows")
                return None

            self.logger.debug(f"Found {len(df)} data rows with columns: {list(df.columns)}")

            # Find relevant columns
            numreads_col = None
            coverage_col = None

            for col in df.columns:
                col_lower = col.lower()
                if "numreads" in col_lower and numreads_col is None:
                    numreads_col = col
                elif "coverage" in col_lower and coverage_col is None:
                    coverage_col = col

            if numreads_col and coverage_col:
                numreads = int(df.iloc[0][numreads_col])
                coverage = int(df.iloc[0][coverage_col])

                coverage_info = CoverageInfo(numreads=numreads, covbases=coverage)
                self.logger.info(f"Extracted coverage info: numreads={numreads}, coverage={coverage}")
                return coverage_info
            else:
                self.logger.warning(f"Required columns not found. Available columns: {list(df.columns)}")
                return None

        except Exception as e:
            self.logger.error(f"Error reading coverage file: {e}")
            return None

    def determine_exon_type(self, filename: str, max_position: int) -> ExonType:
        """
        Determine exon type from filename or position data.

        Args:
            filename: Input filename
            max_position: Maximum position in data

        Returns:
            ExonType enum
        """
        self.logger.info(f"Determining exon type from filename: {filename}")

        filename_lower = filename.lower()
        if "exon6" in filename_lower:
            self.logger.info("✓ Exon type determined: exon6 (from filename)")
            return ExonType.EXON6
        elif "exon7" in filename_lower:
            self.logger.info("✓ Exon type determined: exon7 (from filename)")
            return ExonType.EXON7
        else:
            # Fall back to position-based determination
            exon_type = ExonType.EXON7 if max_position > self.EXON6_MIN_LENGTH else ExonType.EXON6
            self.logger.info(f"Exon type determined by position: {exon_type.value} (max position = {max_position})")
            return exon_type

    def generate_exon6_report(
        self,
        positions: Dict[int, PositionData],
        output_file: Union[str, Path],
        coverage_info: Optional[CoverageInfo] = None
    ) -> None:
        """Generate report specifically for exon 6."""
        output_path = Path(output_file)
        self.logger.info(f"Generating exon 6 report to: {output_path}")

        coverage_display = ""
        if coverage_info:
            coverage_display = f" (reads={coverage_info.numreads}, cov={coverage_info.covbases})"

        try:
            with open(output_path, "w") as f:
                f.write("Exon 6:\n")

                # Primary ABO*O1 marker - position 22 (c.261)
                self._write_position_data(f, 22, positions, coverage_display, "exon6")

                # A subtype positions
                available_subtype_positions = sorted(
                    [p for p in self.EXON6_POSITIONS['a_subtype'] if p in positions]
                )

                if available_subtype_positions:
                    f.write("\n# -------- A subtypes variants in exon 6 --------\n")
                    for pos in available_subtype_positions:
                        self._write_position_data(f, pos, positions, coverage_display, "exon6")

            self.logger.info(f"✓ Exon 6 report successfully written to {output_path}")

        except Exception as e:
            self.logger.error(f"Error generating Exon 6 report: {e}")
            self._create_empty_file(output_path)

    def generate_exon7_report(
        self,
        positions: Dict[int, PositionData],
        output_file: Union[str, Path],
        coverage_info: Optional[CoverageInfo] = None
    ) -> None:
        """Generate report specifically for exon 7."""
        output_path = Path(output_file)
        self.logger.info(f"Generating exon 7 report to: {output_path}")

        coverage_display = ""
        if coverage_info:
            coverage_display = f" (reads={coverage_info.numreads}, cov={coverage_info.covbases})"

        try:
            with open(output_path, "w") as f:
                f.write("Exon 7:\n")

                # Primary diagnostic positions
                for pos in self.EXON7_POSITIONS['primary']:
                    if pos in positions:
                        self._write_position_data(f, pos, positions, coverage_display, "exon7")

                # A subtype positions
                available_subtype_positions = sorted(
                    [p for p in self.EXON7_POSITIONS['a_subtype'] if p in positions]
                )

                if available_subtype_positions:
                    f.write("\n# -------- A subtypes variants --------\n")
                    for pos in available_subtype_positions:
                        self._write_position_data(f, pos, positions, coverage_display, "exon7")

            self.logger.info(f"✓ Exon 7 report successfully written to {output_path}")

        except Exception as e:
            self.logger.error(f"Error generating Exon 7 report: {e}")
            self._create_empty_file(output_path)

    def _write_position_data(
        self,
        file_handle,
        pos: int,
        positions: Dict[int, PositionData],
        coverage_display: str,
        exon_type: str
    ) -> None:
        """Write position data to file with interpretations."""
        if pos not in positions:
            self.logger.warning(f"Position {pos} not found in data")
            return

        pos_data = positions[pos]

        # Write position line - MUST match exact format expected by aggregation script
        if exon_type == "exon6":
            file_handle.write(f"\nExon 6 position(1-based): {pos}\n")
        else:
            file_handle.write(f"\nExon 7 position(1-based): {pos}\n")

        # Write interpretation based on position and exon type
        self._write_interpretation(file_handle, pos, exon_type)

        # Write raw data - MUST match exact format expected by aggregation script
        file_handle.write(f"(1-based) Position:{pos}, Reference Base={pos_data.ref_base}\n")
        file_handle.write(f"Aligned Read Count:{pos_data.coverage}{coverage_display}\n")
        file_handle.write("Mat\tMis\tIns\tDel\tA\tG\tC\tT\n")
        file_handle.write(
            f"{self.format_number(pos_data.match_percent)}\t"
            f"{self.format_number(pos_data.mismatch_percent)}\t"
            f"{self.format_number(pos_data.insertion_percent)}\t"
            f"{self.format_number(pos_data.deletion_percent)}\t"
            f"{self.format_number(pos_data.A_percent)}\t"
            f"{self.format_number(pos_data.G_percent)}\t"
            f"{self.format_number(pos_data.C_percent)}\t"
            f"{self.format_number(pos_data.T_percent)}\n"
        )

    def _write_interpretation(self, file_handle, pos: int, exon_type: str) -> None:
        """Write interpretation text for specific positions."""
        interpretations = {
            # Exon 6 interpretations
            22: ("G nucleotide: A or B blood type.", "Deletion    : O blood type(O1)."),
            27: ("C nucleotide: A1 or A3 subtype.", "T nucleotide: A2 subtype."),
            29: ("T nucleotide: A1 or A3 subtype.", "C nucleotide: A2 subtype."),
            58: ("A nucleotide: A1 or A3 subtype.", "G nucleotide: A2 subtype."),

            # Exon 7 interpretations
            422: ("A nucleotide: B blood type.", "C nucleotide: A or O blood type."),
            428: ("A nucleotide: O blood type (O2).", "G nucleotide: A or B or O blood type."),
            429: ("G nucleotide: A or O blood type.", "C nucleotide: B blood type."),
            431: ("G nucleotide: O blood type (O3).", "A nucleotide: O blood type (O4).", "T nucleotide: A or B or O blood type."),
            93: ("C nucleotide: A1 subtype.", "T nucleotide: A2 or A3 subtype."),
            165: ("G nucleotide: A1 or A2 subtype.", "A nucleotide: A3 subtype."),
            272: ("T nucleotide: A1 subtype.", "A nucleotide: A2 subtype."),
            307: ("G nucleotide: A1 or A2 subtype.", "A nucleotide: A3 subtype."),
            371: ("C nucleotide: A1 or A2 subtype.", "T nucleotide: A3 subtype."),
            446: ("G nucleotide: A1 or A2 subtype.", "A nucleotide: A3 subtype."),
            680: ("C nucleotide: A1 or A3 subtype.", "T nucleotide: A2 subtype."),
            687: ("C nucleotide: A1 subtype.", "Deletion: A2 or A3 subtype (weaker expression)."),
        }

        if pos in interpretations:
            for interpretation in interpretations[pos]:
                file_handle.write(f"{interpretation}\n")

    def _create_empty_file(self, output_path: Path) -> None:
        """Create an empty output file."""
        try:
            output_path.touch()
            self.logger.info(f"Empty file created: {output_path}")
        except Exception as e:
            self.logger.error(f"Failed to create empty file {output_path}: {e}")

    def process_sample(
        self,
        input_file: Union[str, Path],
        output_file: Union[str, Path],
        coverage_file: Optional[Union[str, Path]] = None,
        exon_type: Optional[str] = None
    ) -> bool:
        """
        Process a single sample for ABO phenotype prediction.

        Args:
            input_file: Input nucleotide frequency file
            output_file: Output report file
            coverage_file: Optional coverage statistics file
            exon_type: Optional explicit exon type specification

        Returns:
            True if processing successful, False otherwise
        """
        try:
            self.logger.info("=" * 60)
            self.logger.info("Starting ABO phenotype prediction")
            self.logger.info("=" * 60)

            # Step 1: Read nucleotide frequencies
            positions, max_position, empty_file = self.read_nucleotide_frequencies(input_file)

            if empty_file or not positions:
                self.logger.warning("No data available. Creating empty output file.")
                self._create_empty_file(Path(output_file))
                return False

            # Step 2: Read coverage information if provided
            coverage_info = None
            if coverage_file:
                coverage_info = self.read_coverage_file(coverage_file)

                # Update positions with coverage data
                if coverage_info:
                    for pos_data in positions.values():
                        pos_data.coverage = coverage_info.numreads

            # Step 3: Determine exon type
            if exon_type:
                determined_exon_type = ExonType(exon_type)
                self.logger.info(f"Using explicitly specified exon type: {determined_exon_type.value}")
            else:
                determined_exon_type = self.determine_exon_type(str(input_file), max_position)

            # Step 4: Filter relevant positions and generate report
            if determined_exon_type == ExonType.EXON6:
                self.generate_exon6_report(positions, output_file, coverage_info)
            else:
                self.generate_exon7_report(positions, output_file, coverage_info)

            self.logger.info(f"✓ ABO phenotype metrics written to: {output_file}")
            return True

        except Exception as e:
            self.logger.error(f"Error processing sample: {e}")
            self._create_empty_file(Path(output_file))
            return False


def main():
    """Main function to process nucleotide frequencies into ABO phenotypes."""
    parser = argparse.ArgumentParser(
        description="Extract metrics for ABO typing positions from nucleotide frequency data.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
    %(prog)s -i input.txt -o output.txt
    %(prog)s -i input.txt -o output.txt -c coverage.txt -e exon6
    %(prog)s -i input.txt -o output.txt --verbose
        """
    )

    parser.add_argument(
        "-i", "--input",
        required=True,
        help="Input SAMtools mpileup nucleotide variants metrics file"
    )
    parser.add_argument(
        "-o", "--output",
        required=True,
        help="Output filename for ABO phenotype report"
    )
    parser.add_argument(
        "-c", "--coverage",
        help="Input SAMtools coverage statistics file"
    )
    parser.add_argument(
        "-e", "--exon",
        choices=["exon6", "exon7"],
        help="Explicitly specify which exon data is being processed"
    )
    parser.add_argument(
        "--verbose", "-v",
        action="store_true",
        help="Enable verbose logging"
    )
    parser.add_argument(
        "--version",
        action="version",
        version=f"%(prog)s {__version__}"
    )

    args = parser.parse_args()

    # Set logging level
    loglevel = "DEBUG" if args.verbose else "INFO"

    # Initialize predictor
    predictor = ABOPhenotypePredictor(loglevel=loglevel)

    # Process sample
    success = predictor.process_sample(
        input_file=args.input,
        output_file=args.output,
        coverage_file=args.coverage,
        exon_type=args.exon
    )

    if success:
        predictor.logger.info(f"Script execution completed successfully at: {datetime.datetime.now()}")
        sys.exit(0)
    else:
        predictor.logger.error("Script execution failed")
        sys.exit(1)


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\n! Script interrupted by user")
        sys.exit(130)
    except Exception as e:
        print(f"! CRITICAL ERROR: Unhandled exception: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)
